"""Writes `console/agentic_configurations.yaml`: the console's own agents plus every topic's tools, decider and worker, in one file.

    python scaffold.py console           # (also part of a plain `python scaffold.py`)

Each topic folder still has its own `agentic_configuration.yaml` — that is what its agent handles, `cli.py tools` and the tests read. The
console file is built *from* those, never typed, so the two cannot disagree:

  - `tools:`  every topic's tools, grouped by topic. Tool names are unique across topics (`ml_core.specs.TOPIC_QUALIFIED` prefixes the
              ones that were not), because `agent_builder` keeps a single registry per config keyed by name.
  - `agents:` the console agents (`scaffold_parts/console.py`), then each topic's decider and worker. A topic decider depends on
              `requirement_agent` and `ml_decider_agent`, and its worker on those two and its decider — so the problem, the data details and
              the console decider's verdict reach every sub agent through `{agent_output}` without the prompts naming anyone.
  - `orchestrators:` / `pipeline:` the console workflow (gate → `ml_decider_agent` → the sub agents it chooses) and each topic's own.
"""

from __future__ import annotations

import re

import yaml

from scaffold_content import TOPICS
from scaffold_parts.console import AGENTS, LLMS, UPSTREAM

HEADER = """# ml-agent console — the console's own agents and EVERY sub agent (one decider + one worker per problem type), in one config.
#
# Generated by `python scaffold.py console` from the topic folders (`<category>/<problem_type>/agentic_configuration.yaml`) and the prose in
# `scaffold_parts/console.py`. Edit those and re-run it rather than editing this file: the `tools:` block is read off the tool functions,
# so it cannot drift from what the code does, and the sub agents below are copies of what each topic folder declares.
#
# How a run flows (console/run.py):
#
#   chat_agent ── talks to the user until requirement_agent says there is a problem and a data source
#   requirement_agent ── {"requirements": true, "problem": ..., "data_details": ...}
#   ml_decider_agent ── reads that plus the data's own columns, and names the sub agents to use (one or several, in order)
#   <topic>_decider_agent ── for each chosen sub agent: read-only checks on the data, then a plan a human approves
#   <topic>_agent ── carries the plan out with that topic's tools; a later sub agent is also given the earlier ones' results
#
# Everything the sub agents need arrives the same way: `{question}` and `{context}` (the data path and its columns, the problem, the
# conversation, what earlier sub agents found) and `{agent_output}` (what `dependency_agent` lists below).

"""


def topic_agents(key: str) -> tuple[str, str]:
    slug = TOPICS[key]["slug"]
    return f"{slug}_decider_agent", f"{slug}_agent"


def tools_block(topic_yaml: str) -> str:
    """The text of one topic's `tools:` entries, exactly as that topic's own config has them."""
    match = re.search(r"^tools:\n(.*?)^agents:\n", topic_yaml, re.S | re.M)
    if not match:
        raise ValueError("a topic config without a `tools:` block followed by `agents:`")
    return match.group(1).rstrip() + "\n"


def listing(names: list[str]) -> str:
    return "\n".join(f'      - "{name}"' for name in names)


def render_sub_agents(key: str, topic_cfg: dict) -> str:
    """One topic's two agents, with the prompts addressed from `console/` and the upstream agents added to what each depends on."""
    category, name = key.split(".")
    decider, worker = topic_agents(key)
    upstream = "\n".join(f'      - "{agent}"' for agent in UPSTREAM)
    where = f"../{category}/{name}"
    return f'''  {decider}:  # {key}: runs read-only checks on the data and writes the plan; starts from what the console decided
    type: "{topic_cfg["agents"][decider]["type"]}"
    llm: "{topic_cfg["agents"][decider]["llm"]}"
    substitute_llm: "{topic_cfg["agents"][decider]["substitute_llm"]}"
    prompt_path: "{where}/decider_prompt.md"
    dependency_agent:
{upstream}
    tools:
{listing(topic_cfg["agents"][decider]["tools"])}

  {worker}:  # {key}: carries out the plan with every tool of the topic
    type: "{topic_cfg["agents"][worker]["type"]}"
    llm: "{topic_cfg["agents"][worker]["llm"]}"
    substitute_llm: "{topic_cfg["agents"][worker]["substitute_llm"]}"
    prompt_path: "{where}/prompt.md"
    dependency_agent:
{upstream}
      - "{decider}"
    tools:
{listing(topic_cfg["agents"][worker]["tools"])}
'''


def banner(key: str) -> str:
    return f"  # ======== {key.replace('.', '/')}: {TOPICS[key]['title']} ".ljust(120, "=")


def render_console(topic_yamls: dict[str, str]) -> str:
    """The whole console config, from each topic's rendered YAML (keyed `<category>.<problem_type>`)."""
    keys = sorted(topic_yamls)
    configs = {key: yaml.safe_load(topic_yamls[key]) for key in keys}

    tool_names: dict[str, str] = {}
    tool_sections = []
    for key in keys:
        block = tools_block(topic_yamls[key])
        for tool in re.findall(r'^  - name: "([^"]+)"', block, re.M):
            if tool in tool_names:
                raise ValueError(
                    f"tool name {tool!r} is defined by both {tool_names[tool]} and {key}; the console config is keyed by name, so one would "
                    "replace the other — add the function name to `ml_core.specs.TOPIC_QUALIFIED`"
                )
            tool_names[tool] = key
        tool_sections.append(f"{banner(key)}\n{block}")

    agent_sections = [AGENTS.rstrip() + "\n"]
    for key in keys:
        agent_sections.append(f"{banner(key)}\n{render_sub_agents(key, configs[key])}")

    pool = []
    for key in keys:
        decider, worker = topic_agents(key)
        pool.append(f'      # {key.replace(".", "/")}\n      - "{decider}"\n      - "{worker}"')

    workflows = []
    for key in keys:
        decider, worker = topic_agents(key)
        workflows.append(f'''  {TOPICS[key]["slug"]}_workflow:  # {key.replace(".", "/")}: decide the approach, then run it
    sub_agents:
      - "{decider}"
      - "{worker}"
''')

    choices = "\n".join(f'            - "{TOPICS[key]["slug"]}_workflow"' for key in keys)
    steps = []
    for key in keys:
        decider, worker = topic_agents(key)
        steps.append(f'''  - name: "{TOPICS[key]["slug"]}_workflow"
    loops: 1
    description: "{TOPICS[key]["title"]}: decide the approach, then run it."
    steps:
      - name: "decide"
        processor:
          type: "agent"
          name: "{decider}"
      - name: "solve"
        processor:
          type: "agent"
          name: "{worker}"
''')

    return (
        HEADER
        + LLMS
        + "\ntools:\n"
        + "\n".join(tool_sections)
        + "\nagents:\n"
        + "\n".join(agent_sections)
        + f'''

orchestrators:
  ml_agent_workflow:  # the console: the gate, then the decider, which picks from `sub_agents` — every pair below — and the picked pairs run in the order it names them
    decider: "ml_decider_agent"
    sub_agents:
{chr(10).join(pool)}

{chr(10).join(workflows)}

pipeline:
  - name: "ml_agent_workflow"
    loops: 1
    description: "Gate on a problem and a data source, decide which sub agents the problem goes to, then run each one (decide → human approval → solve)."
    steps:
      - name: "gate"
        processor:
          type: "agent"
          name: "requirement_agent"
      - name: "decide"
        processor:
          type: "agent"
          name: "ml_decider_agent"
      - name: "solve"
        processor:
          type: "orchestrator"
          selected_by: "ml_decider_agent"
          choices:
{choices}

{chr(10).join(steps)}'''
    ).rstrip() + "\n"

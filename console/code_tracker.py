"""Tracks the decisions ML Agent's pipeline actually makes — the requirements gate's own verdict and the
sub agents `ml_decider_agent` chose (and how each one's run ended) — so `code_generator_agent` (and the deterministic fallback
below it) can write a starter script grounded in what was actually decided, not in a model's prose about
it.

`run_pipeline` in `console/run.py` records one `DecisionRecord` per approved stage, right after the
human approves it:

    tracker = DecisionTracker()
    tracker.record(stage="sub agents", agent="ml_decider_agent", decision={"sub_agents": ["supervised/classification"]})
    ...
    tracker.fallback_script(problem=..., data_details=..., category=..., problem_type=...)
    tracker.covers(script, category=..., problem_type=...)
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass
class DecisionRecord:
    """One stage's structured, human-approved verdict."""

    stage: str
    agent: str
    decision: dict[str, Any] = field(default_factory=dict)


class DecisionTracker:
    """Collects every stage's approved decision, in the order the pipeline made them."""

    def __init__(self) -> None:
        self.decisions: list[DecisionRecord] = []

    def record(self, stage: str, agent: str, decision: dict[str, Any]) -> None:
        """Record one approved decision."""
        self.decisions.append(DecisionRecord(stage=stage, agent=agent, decision=dict(decision)))

    def render_decisions(self) -> str:
        """Every decision rendered as plain text — a compact record of what the pipeline settled on."""
        if not self.decisions:
            return "(no decisions were recorded during this run)"

        blocks = []
        for index, record in enumerate(self.decisions, start=1):
            fields = ", ".join(f"{key}={value!r}" for key, value in record.decision.items())
            blocks.append(f"{index}. [{record.stage} / {record.agent}] {fields}")
        return "\n".join(blocks)

    def fallback_script(self, problem: str, data_details: str, category: str, problem_type: str) -> str:
        """The starter script this class can write entirely on its own, from the pipeline's actual
        decisions rather than from a model's account of them — the deterministic fallback
        `generate_code()` writes when `code_generator_agent` fails to answer, or answers with a script
        that `covers()` says is not grounded in what was actually decided.
        """
        return (
            f'"""Generated by ml-agent: a starting point for a {category}/{problem_type} problem.\n\n'
            f"Problem: {problem}\n"
            f"Data: {data_details}\n"
            '"""\n'
            "\n"
            "\n"
            "def main() -> None:\n"
            f"    # Category: {category}\n"
            f"    # Problem type: {problem_type}\n"
            f"    # Data: {data_details}\n"
            "    # TODO: load the data above, then build and evaluate a solution for this problem type.\n"
            '    raise NotImplementedError("fill in the pipeline for this problem type")\n'
            "\n"
            "\n"
            'if __name__ == "__main__":\n'
            "    main()\n"
        )

    def covers(self, script: str, category: str, problem_type: str) -> bool:
        """Whether `script` at least grounds itself in what was actually decided — the check that
        decides whether a model-authored script is trustworthy enough to write out as-is, or whether
        `fallback_script`'s own deterministic version should be written instead.
        """
        return bool(script.strip()) and category in script and problem_type in script
